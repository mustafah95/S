#!/usr/bin/env node
/**
 * Regenerates apps/server/src/db/schema.ts from the SQL migrations (SQL is the source of truth).
 *
 *   1. creates a scratch database and applies every migration in apps/server/migrations
 *   2. runs `drizzle-kit pull` against it
 *   3. post-processes the output: custom types for citext/bytea/tstzrange, Date timestamps, numeric as number,
 *      constraints stripped (they live in SQL and are enforced by PostgreSQL)
 *
 * Usage: DATABASE_URL=postgres://postgres@127.0.0.1:54329/postgres node scripts/gen-drizzle-schema.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const serverDir = join(root, 'apps/server');
const adminUrl = new URL(process.env.DATABASE_URL ?? 'postgres://postgres@127.0.0.1:54329/postgres');
const dbName = `sofia_schema_gen_${Date.now()}`;
const psql = (db, args) =>
  execFileSync('psql', ['-v', 'ON_ERROR_STOP=1', '-q', '-d', withDb(db), ...args], { stdio: 'inherit' });
function withDb(db) {
  const u = new URL(adminUrl);
  u.pathname = `/${db}`;
  return u.toString();
}

psql(adminUrl.pathname.slice(1) || 'postgres', ['-c', `CREATE DATABASE ${dbName}`]);
try {
  for (const f of readdirSync(join(serverDir, 'migrations')).filter((f) => /^\d+_.+\.sql$/.test(f)).sort()) {
    psql(dbName, ['-f', join(serverDir, 'migrations', f)]);
  }
  const out = mkdtempSync(join(tmpdir(), 'sofia-drizzle-'));
  const cfg = join(out, 'drizzle.config.mjs');
  writeFileSync(
    cfg,
    `export default { dialect: 'postgresql', out: ${JSON.stringify(out)}, dbCredentials: { url: ${JSON.stringify(
      withDb(dbName),
    )} }, introspect: { casing: 'camel' } };`,
  );
  execFileSync('npx', ['drizzle-kit', 'pull', '--config', cfg], { cwd: serverDir, stdio: 'inherit' });
  let src = readFileSync(join(out, 'schema.ts'), 'utf8');

  src = src.replace(/\}, \(table\) => \[[\s\S]*?\n\]\);/g, '});');
  src = src.replace(/\t\/\/ TODO: failed to parse database type '(\w+)'\n\t(\w+): unknown\("(\w+)"\)/g, (_m, type, prop, col) => {
    const fn = { citext: 'citext', bytea: 'bytea', tstzrange: 'tstzrange' }[type];
    if (!fn) throw new Error(`Unhandled database type ${type}`);
    return `\t${prop}: ${fn}("${col}")`;
  });
  src = src.replace(/mode: 'string'/g, "mode: 'date'");
  src = src.replace(/numeric\(("\w+", )?\{ precision:\s*(\d+), scale:\s*(\d+) \}\)((?:\.default\('[-\d.]+'\))?)/g, (_m, col, p, s, def) =>
    `numeric(${col ?? ''}{ precision: ${p}, scale: ${s}, mode: 'number' })${def ? def.replace(/'/g, '') : ''}`);
  src = src.replace(/\t\/\/ You can use \{ mode: "bigint" \} if numbers are exceeding js number limitations\n/g, '');
  src = src.replace(/^import \{[^}]+\} from "drizzle-orm\/pg-core"\nimport \{ sql \} from "drizzle-orm"\n/m, '');

  const header = `/* eslint-disable */
// GENERATED by scripts/gen-drizzle-schema.mjs from apps/server/migrations/*.sql — do not edit by hand.
// Constraints, indexes, triggers and policies are defined (and enforced) in the SQL migrations.
import { pgTable, uuid, text, jsonb, integer, boolean, bigint, timestamp, date, inet, bigserial, numeric, real, smallint, primaryKey, pgSequence, customType } from 'drizzle-orm/pg-core';

const citext = customType<{ data: string }>({ dataType: () => 'citext' });
const bytea = customType<{ data: Buffer; driverData: Buffer }>({ dataType: () => 'bytea' });
/** PostgreSQL tstzrange in canonical text form, e.g. ["2026-11-18 17:00:00+00","2026-11-18 19:00:00+00") */
const tstzrange = customType<{ data: string }>({ dataType: () => 'tstzrange' });
`;
  src = header + src.replace(/^\n+/, '\n');
  const target = join(serverDir, 'src/db/schema.ts');
  writeFileSync(target, src);
  console.log(`Wrote ${target}`);
} finally {
  psql(adminUrl.pathname.slice(1) || 'postgres', ['-c', `DROP DATABASE IF EXISTS ${dbName}`]);
}
